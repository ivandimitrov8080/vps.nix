import collections.abc
import inspect
import io
import os
import types
import typing
from contextlib import redirect_stdout

from test_driver.debug import DebugNop
from test_driver.driver import Driver, load_driver_configuration, pythonize_name
from test_driver.logger import CompositeLogger, TerminalLogger

cfg = load_driver_configuration(os.environ["NIXOS_TEST_DRIVER_CONFIG"])

modules: set[str] = set()          # collected while rendering annotations


def render(tp: object) -> str:
    """Turn an annotation object back into fully-qualified stub source."""
    if tp is inspect.Parameter.empty or tp is typing.Any:
        return "typing.Any"
    if tp is None or tp is type(None):
        return "None"
    if isinstance(tp, typing.TypeVar):
        return tp.__name__
    if isinstance(tp, str):                       # PEP 563 leftovers
        return tp

    origin, args = typing.get_origin(tp), typing.get_args(tp)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(render(a) for a in args)
    if origin is not None:
        base = render(origin)
        if not args:
            return base
        if origin is collections.abc.Callable:
            params, ret = args
            if params is Ellipsis:
                return f"{base}[..., {render(ret)}]"
            return f"{base}[[{', '.join(render(p) for p in params)}], {render(ret)}]"
        return f"{base}[{', '.join(render(a) for a in args)}]"

    if isinstance(tp, type):
        if tp.__module__ == "builtins":
            return tp.__qualname__
        modules.add(tp.__module__)
        return f"{tp.__module__}.{tp.__qualname__}"
    return "typing.Any"


# An empty driver: no __init__ (so no test-script read), no __enter__ (no machines).
d = object.__new__(Driver)
d.config = cfg
d.logger = CompositeLogger([TerminalLogger()])
d.debug = DebugNop()
d.vlans, d.machines_qemu, d.machines_nspawn, d.polling_conditions = [], [], [], []

with redirect_stdout(io.StringIO()):          # test_symbols() prints a summary
    symbols = d.test_symbols()

class_hints = typing.get_type_hints(Driver)
decls: list[str] = []

for name, value in symbols.items():
    attr = getattr(Driver, name, None)

    if inspect.isclass(value):                # BaseMachine, QemuMachine, NspawnMachine
        decls.append(f"from {value.__module__} import {value.__name__} as {name}")
    elif inspect.ismodule(value):             # os
        decls.append(f"import {value.__name__}")
    elif name in class_hints:                 # machines_qemu, vlans, debug, ...
        decls.append(f"{name}: {render(class_hints[name])}")
    elif isinstance(attr, property):          # machines
        decls.append(f"{name}: {render(typing.get_type_hints(attr.fget)['return'])}")
    elif callable(value):                     # start_all, retry, subtest, ...
        decls.append(f"{name}: typing.Callable[..., typing.Any]")
    else:                                     # driver, log, t
        decls.append(f"{name}: {render(type(value))}")

# Machines come from the config, so we never construct (or start) one.
modules.add("test_driver.machine")
for vm in sorted(cfg.vms):
    decls.append(f"{pythonize_name(vm)}: test_driver.machine.QemuMachine")
for ctr in sorted(cfg.containers):
    decls.append(f"{pythonize_name(ctr)}: test_driver.machine.NspawnMachine")
if len(cfg.vms) + len(cfg.containers) == 1:
    only = pythonize_name(next(iter((*cfg.vms, *cfg.containers))))
    decls.append(f"machine: {only.split(':')[0]}" if False else
                 f"machine: test_driver.machine.{'QemuMachine' if cfg.vms else 'NspawnMachine'}")

print("# @generated by test/builtins.py — do not edit")
print(f"# source: {os.environ['NIXOS_TEST_DRIVER_CONFIG']}\n")
for m in sorted(modules):
    print(f"import {m}")
print()
print("\n".join(decls))
